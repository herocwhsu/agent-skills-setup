#!/usr/bin/env bash
# weekly-review.sh — Deterministic facts for the weekly review report.
#
# Writes docs/weekly/YYYY-Www.md: commits and churn for the last N days, state
# layer thresholds, feature status counts, and the "What's Next" queue. The
# "Plan for next week" section is left as a marker for the caller to fill.
#
# Usage:
#   bash scripts/weekly-review.sh [--days N] [--out-dir DIR]
set -euo pipefail

REPO_DIR="${WEEKLY_REVIEW_REPO_DIR:-$(cd "$(dirname "$0")/.." && pwd)}"
DAYS=7
OUT_DIR="$REPO_DIR/docs/weekly"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --days) DAYS="${2:?--days needs a value}"; shift 2 ;;
    --out-dir) OUT_DIR="${2:?--out-dir needs a value}"; shift 2 ;;
    *) echo "weekly-review.sh: unknown argument: $1" >&2; exit 2 ;;
  esac
done
[[ "$DAYS" =~ ^[0-9]+$ ]] || { echo "weekly-review.sh: --days must be an integer" >&2; exit 2; }

cd "$REPO_DIR"
# Label by yesterday so a Monday-morning run names the week it reports on.
WEEK="$(python3 -c 'import datetime as d; print((d.date.today() - d.timedelta(days=1)).strftime("%G-W%V"))')"
OUT="$OUT_DIR/$WEEK.md"
SINCE="$DAYS days ago"
mkdir -p "$OUT_DIR"

commit_count=$(git log --since="$SINCE" --oneline 2>/dev/null | wc -l | tr -d ' ' || true)

{
  echo "# Weekly review $WEEK"
  echo
  echo "Window: last $DAYS days, $commit_count commits. Generated by scripts/weekly-review.sh."
  echo
  echo "## Commits"
  echo
  if [[ "$commit_count" -eq 0 ]]; then
    echo "_No commits in window._"
  else
    git log --since="$SINCE" --format='- `%h` %ad %s' --date=short
  fi
  echo
  echo "## Files changed"
  echo
  echo '```'
  first=$(git log --since="$SINCE" --format=%H 2>/dev/null | tail -1 || true)
  if [[ -n "$first" ]]; then
    base=$(git rev-parse -q --verify "$first^" || git hash-object -t tree /dev/null)
    git diff --stat "$base" HEAD | tail -15 || true
  fi
  echo '```'
  echo
  echo "## State layer thresholds"
  echo
  echo '```'
  bash scripts/trace-evaluation.sh --check-thresholds 2>&1 || true
  echo '```'
  echo
  echo "## Feature status"
  echo
  echo '```'
  grep -o '"status": *"[a-z_-]*"' feature_list.json 2>/dev/null | sort | uniq -c || true
  echo '```'
  echo
  echo "## Verification command paths"
  echo
  echo "Paths named by a feature's \`verification\` command that no longer exist:"
  echo
  echo '```'
  python3 - <<'PY'
import json, os, re
missing = []
try:
    features = json.load(open("feature_list.json"))["features"]
except (OSError, ValueError, KeyError) as e:
    features = []
    missing.append(f"feature_list.json unreadable: {e}")
for f in features:
    for tok in re.findall(r"(?:scripts|tests|docs)/[\w./*-]+", f.get("verification") or ""):
        tok = tok.rstrip(".,;:")
        if "*" not in tok and not os.path.exists(tok):
            missing.append(f"{f.get('id', '?')}: {tok}")
print("\n".join(missing) if missing else "none")
PY
  echo '```'
  echo
  echo "## Queue from PROGRESS.md"
  echo
  awk '/^### What.s Next/{f=1; next} f && /^(## |### )/{exit} f' PROGRESS.md 2>/dev/null || true
  echo
  echo "## Plan for next week"
  echo
  echo "<!-- weekly-review:plan -->"
} > "$OUT"

echo "$OUT"
